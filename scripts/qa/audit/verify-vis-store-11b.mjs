out.after900Shot = await shot(page, "verify/vis-store/vis-store-11-reproduce-1440-after900");
await browser.close();
writeFileSync("docs/qa/audit/verify/vis-store/vis-store-11-reproduce.json", JSON.stringify(out, null, 2));
