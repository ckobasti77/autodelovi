// Generates lib/icons/phosphor/: one module per Phosphor icon this codebase imports, with only
// the weights it uses (D30: regular; plus bold and fill for emphasis), a shared base, a barrel
// (index.ts) and a package.json declaring the folder side-effect free, so the bundler keeps
// only the icons a chunk imports. next.config.ts aliases "@phosphor-icons/react/dist/ssr" to
// the barrel (PERF-12): every import keeps its path and its types (TypeScript still reads the
// package's .d.ts), while the bundle stops shipping the thin/light/duotone paths.
//
// Usage: node scripts/brand/build-phosphor.mjs          (regenerate)
//        node scripts/brand/build-phosphor.mjs --check  (exit 1 if the folder is out of date)
// Run it after importing a new icon: an icon missing from the folder fails the build with
// "export … was not found".
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { createRequire } from "node:module";

const ROOT = path.resolve(import.meta.dirname, "../..");
const OUT = path.join(ROOT, "lib/icons/phosphor");
const SCAN = ["app", "components", "lib"];
const SPECIFIER = "@phosphor-icons/react/dist/ssr";
const WEIGHTS = ["regular", "bold", "fill"];
const NL = "\n";

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "node_modules" || entry.name.startsWith(".") || full === OUT) continue;
      yield* walk(full);
    } else if (/\.(tsx?|mjs)$/.test(entry.name)) {
      yield full;
    }
  }
}

/** Value names imported from the SSR entry (type-only specifiers are skipped). */
async function usedIcons() {
  const names = new Set();
  const escaped = SPECIFIER.replace(/[/.]/g, (c) => `\\${c}`);
  const pattern = new RegExp(`import\\s+(type\\s+)?\\{([^}]*)\\}\\s+from\\s+["']${escaped}["']`, "g");
  for (const dir of SCAN) {
    for await (const file of walk(path.join(ROOT, dir))) {
      const source = await readFile(file, "utf8");
      for (const match of source.matchAll(pattern)) {
        if (match[1]) continue;
        for (const raw of match[2].split(",")) {
          const spec = raw.trim();
          if (!spec || spec.startsWith("type ")) continue;
          names.add(spec.split(/\s+as\s+/)[0].trim());
        }
      }
    }
  }
  return [...names].sort();
}

/** React element → createElement source (Fragment / svg primitives with plain props). */
function serialize(node, React) {
  if (node === null || node === undefined || node === false) return "null";
  if (typeof node === "string") return JSON.stringify(node);
  const { children, ...props } = node.props ?? {};
  const type = node.type === React.Fragment ? "Fragment" : JSON.stringify(node.type);
  const propsSource = Object.keys(props).length ? JSON.stringify(props) : "null";
  const kids = children === undefined ? [] : Array.isArray(children) ? children : [children];
  return `h(${[type, propsSource, ...kids.map((child) => serialize(child, React))].join(", ")})`;
}

const HEADER = "// GENERATED by scripts/brand/build-phosphor.mjs — do not edit.";

const BASE_SOURCE = `${HEADER} Regenerate after importing a
// new icon from "${SPECIFIER}" (next.config.ts aliases that path to ./index.ts for the
// bundler; types still come from the package). Weights: ${WEIGHTS.join(", ")} (PERF-12).
import { createElement as h, forwardRef, type ReactElement, type SVGProps } from "react";

export type IconWeight = "thin" | "light" | "regular" | "bold" | "fill" | "duotone";
type IconProps = Omit<SVGProps<SVGSVGElement>, "ref"> & {
  alt?: string;
  color?: string;
  size?: string | number;
  weight?: IconWeight;
  mirrored?: boolean;
};

/** Same markup as Phosphor's SSRBase; a weight that was not generated falls back to regular. */
export function icon(displayName: string, weights: Map<IconWeight, ReactElement>) {
  const Component = forwardRef<SVGSVGElement, IconProps>(function PhosphorIcon(props, ref) {
    const {
      alt,
      color = "currentColor",
      size = "1em",
      weight = "regular",
      mirrored = false,
      children,
      ...rest
    } = props;
    return h(
      "svg",
      {
        ref,
        xmlns: "http://www.w3.org/2000/svg",
        width: size,
        height: size,
        fill: color,
        viewBox: "0 0 256 256",
        transform: mirrored ? "scale(-1, 1)" : undefined,
        ...rest,
      },
      alt ? h("title", null, alt) : null,
      children,
      weights.get(weight) ?? weights.get("regular"),
    );
  });
  Component.displayName = displayName;
  return Component;
}
`;

const PACKAGE_JSON =
  JSON.stringify(
    {
      name: "sklop-phosphor-icons",
      private: true,
      description:
        "Generated by scripts/brand/build-phosphor.mjs (PERF-12). Side-effect free so unused icons are dropped.",
      sideEffects: false,
    },
    null,
    2,
  ) + NL;

/** { file name → source } for the whole folder. */
async function build() {
  const require = createRequire(path.join(ROOT, "package.json"));
  const React = require("react");
  const pkgDir = path.dirname(require.resolve("@phosphor-icons/react/package.json"));
  const icons = await usedIcons();
  const files = new Map([
    ["base.ts", BASE_SOURCE],
    ["package.json", PACKAGE_JSON],
  ]);
  const barrel = [];
  for (const exportName of icons) {
    const base = exportName.replace(/Icon$/, "");
    const defsFile = path.join(pkgDir, "dist/defs", `${base}.es.js`);
    const defs = (await import(pathToFileURL(defsFile).href)).default;
    if (!(defs instanceof Map)) throw new Error(`${exportName}: no weight map in ${defsFile}`);
    const entries = WEIGHTS.map((weight) => {
      const element = defs.get(weight);
      if (!element) throw new Error(`${exportName}: weight ${weight} missing`);
      return `  [${JSON.stringify(weight)}, ${serialize(element, React)}],`;
    });
    files.set(
      `${base}.ts`,
      [
        HEADER,
        'import { createElement as h, Fragment, type ReactElement } from "react";',
        "",
        'import { icon, type IconWeight } from "./base";',
        "",
        `export const ${exportName} = /* @__PURE__ */ icon(${JSON.stringify(exportName)}, new Map<IconWeight, ReactElement>([`,
        ...entries,
        "]));",
        "",
      ].join(NL),
    );
    barrel.push(`export { ${exportName} } from "./${base}";`);
  }
  files.set(
    "index.ts",
    [
      HEADER,
      ...barrel,
      "",
      "// Safety net for an icon imported after the last run: it still resolves (all six weights)",
      "// through the package's own SSR entry, which the alias does not cover. Named exports above",
      "// take precedence over this star export.",
      'export * from "@phosphor-icons/react/ssr";',
      "",
    ].join(NL),
  );
  return files;
}

const files = await build();
if (process.argv.includes("--check")) {
  let stale = false;
  for (const [name, source] of files) {
    const current = await readFile(path.join(OUT, name), "utf8").catch(() => "");
    if (current !== source) stale = true;
  }
  const existing = await readdir(OUT).catch(() => []);
  if (existing.some((name) => !files.has(name))) stale = true;
  if (stale) {
    console.error("lib/icons/phosphor is out of date: run node scripts/brand/build-phosphor.mjs");
    process.exit(1);
  }
  console.log("lib/icons/phosphor is up to date");
} else {
  await rm(OUT, { recursive: true, force: true });
  await mkdir(OUT, { recursive: true });
  for (const [name, source] of files) await writeFile(path.join(OUT, name), source);
  console.log(`lib/icons/phosphor: ${files.size - 3} icons`);
}
