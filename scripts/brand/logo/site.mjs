// Turns the logo kit in public/brand into the files the site itself needs (step 33: the star arc).
//
// Usage: node scripts/brand/logo/site.mjs   (after build.mjs)
// Output:
//   components/brand/logoPaths.ts   path data of the lockups for the inline <Logo> components
//   app/icon.svg                    512 master tile that switches to the marks drawn for tab sizes
//   app/favicon.ico                 copy of public/brand/favicon.ico (16, 32, 48 — drawn per pixel grid)
//   app/apple-icon.png              copy of public/brand/apple-touch-icon.png (180, opaque)
import { copyFile, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { optimizeSvg } from "./lib/export.mjs";
import { hintedIconSvg, iconSvg } from "./logo.mjs";

const ROOT = path.resolve(import.meta.dirname, "../../..");
const PUBLIC = path.join(ROOT, "public/brand");
const INK = "#f1ece3";

/** `{ w, h, d }` of a night-variant kit file: one path, the ink. */
async function read(name) {
  const svg = await readFile(path.join(PUBLIC, `${name}-night.svg`), "utf8");
  const box = /viewBox="0 0 ([\d.]+) ([\d.]+)"/.exec(svg);
  if (!box) throw new Error(`${name}: no viewBox`);
  const paths = [...svg.matchAll(/<path fill="(#[0-9a-f]{6})"[^>]*? d="([^"]+)"\/>/g)];
  if (paths.length !== 1 || paths[0][1] !== INK)
    throw new Error(`${name}: expected exactly one path in ${INK}, found ${paths.length}`);
  return { w: Number(box[1]), h: Number(box[2]), d: paths[0][2] };
}

const horizontal = await read("logo-horizontal");
const stacked = await read("logo-stacked");
const mark = await read("mark-small");

// ---------------------------------------------------------------------------------------------
// components/brand/logoPaths.ts
// ---------------------------------------------------------------------------------------------
const entry = (doc, form) => `/** ${doc} */
export const ${form.name} = {
  w: ${form.w},
  h: ${form.h},
  d: "${form.d}",
} as const;
`;
const ts = `/**
 * Path data of the Euromotors Plus · OEM Parts logo for the inline components in
 * \`components/brand/Logo.tsx\`. Generated by \`node scripts/brand/logo/site.mjs\` from the kit in
 * \`public/brand/\` — do not edit; change \`scripts/brand/logo/logo.mjs\` and rebuild.
 *
 * Units are the kit's own. One path per form, filled with \`currentColor\` and \`evenodd\`: the
 * logo has a single ink and no accent.
 */

${entry("Compact mark + EUROMOTORS / PLUS — rule — OEM Parts (`logo-horizontal-*`): the header lockup.", { name: "LOGO_HORIZONTAL", ...horizontal })}
${entry("The arc of 12 stars around EUROMOTORS / — PLUS — / OEM Parts (`logo-stacked-*`): the primary logo.", { name: "LOGO_STACKED", ...stacked })}
${entry("The simplified mark, five stars (`mark-small-*`): 32 px and below.", { name: "LOGO_MARK", ...mark })}`;
await writeFile(path.join(ROOT, "components/brand/logoPaths.ts"), ts);
console.log(
  `components/brand/logoPaths.ts ${(Buffer.byteLength(ts) / 1024).toFixed(1)} KB (horizontal ${(horizontal.d.length / 1024).toFixed(1)} KB, stacked ${(stacked.d.length / 1024).toFixed(1)} KB, mark ${(mark.d.length / 1024).toFixed(1)} KB)`,
);

// ---------------------------------------------------------------------------------------------
// app/icon.svg, app/favicon.ico, app/apple-icon.png
// ---------------------------------------------------------------------------------------------
/** Shapes of a generated icon document, without the wrapper and the title. */
const shapes = (svg) => (svg.match(/<path\b[^>]*\/>/g) ?? []).join("");
const SIZE = 512;
const hinted = (px) =>
  `<g class="h${px}" transform="scale(${Number((SIZE / px).toFixed(4))})">${shapes(optimizeSvg(hintedIconSvg(px)))}</g>`;
// A browser draws the icon into a tab-sized viewport, so the media queries see 16, 32 or 48 px and
// swap the vector master for the mark drawn on that pixel grid (the mechanism of D53).
const iconSvgFile = [
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}" width="${SIZE}" height="${SIZE}">`,
  `  <!-- Generated by scripts/brand/logo/site.mjs from scripts/brand/logo/logo.mjs. Do not edit. -->`,
  `  <title>Euromotors Plus</title>`,
  `  <style>.h16,.h32,.h48{display:none}@media (max-width:56px){.m{display:none}.h48{display:inline}}@media (max-width:40px){.h48{display:none}.h32{display:inline}}@media (max-width:24px){.h32{display:none}.h16{display:inline}}</style>`,
  `  <g class="m">${shapes(optimizeSvg(iconSvg()))}</g>`,
  `  ${hinted(16)}`,
  `  ${hinted(32)}`,
  `  ${hinted(48)}`,
  `</svg>`,
  ``,
].join("\n");
await writeFile(path.join(ROOT, "app/icon.svg"), iconSvgFile);
await copyFile(path.join(PUBLIC, "favicon.ico"), path.join(ROOT, "app/favicon.ico"));
await copyFile(path.join(PUBLIC, "apple-touch-icon.png"), path.join(ROOT, "app/apple-icon.png"));
console.log(
  `app/icon.svg ${(Buffer.byteLength(iconSvgFile) / 1024).toFixed(1)} KB, app/favicon.ico, app/apple-icon.png written`,
);
