import type { NextConfig } from "next";

import { staticSecurityHeaders, TOKEN_ROUTE_SOURCES } from "./lib/security/headers";

/** Convex file storage host for next/image (ARCHITECTURE §G7, §G11). */
function convexImageHost(): URL | null {
  const raw = process.env.NEXT_PUBLIC_CONVEX_URL;
  if (!raw) return null;
  try {
    return new URL(raw);
  } catch {
    return null;
  }
}

const convexHost = convexImageHost();

/**
 * public/models and public/images keep stable names (not content-hashed), so they get a short
 * max-age plus stale-while-revalidate instead of `immutable` (PERF-19): repeat visits paint the
 * poster and start the GLB from cache, and a re-exported asset reaches everyone within a day.
 */
const PUBLIC_ASSET_CACHE = "public, max-age=86400, stale-while-revalidate=604800";

const nextConfig: NextConfig = {
  poweredByHeader: false,
  turbopack: {
    resolveAlias: {
      // Single-weight-family Phosphor build (regular, bold, fill) generated by
      // scripts/brand/build-phosphor.mjs; same named exports, types still from the package
      // (PERF-12). Regenerate after importing a new icon.
      "@phosphor-icons/react/dist/ssr": "./lib/icons/phosphor/index.ts",
    },
  },
  images: {
    formats: ["image/avif", "image/webp"],
    qualities: [60, 75, 85],
    remotePatterns: convexHost
      ? [{ protocol: "https", hostname: convexHost.hostname, pathname: "/api/storage/**" }]
      : [],
  },
  experimental: {
    authInterrupts: true,
    optimizePackageImports: ["@phosphor-icons/react"],
  },
  async redirects() {
    return [
      // Step 03 concept route — its content lives on in the styleguide.
      { source: "/lab/koncept", destination: "/styleguide", permanent: true },
    ];
  },
  async headers() {
    // Security headers on every response (SECURITY §L3); the nonce CSP is set per request in
    // proxy.ts. Later entries override earlier ones for the same key.
    return [
      { source: "/:path*", headers: staticSecurityHeaders(process.env.NODE_ENV === "production") },
      ...TOKEN_ROUTE_SOURCES.map((source) => ({
        source,
        headers: [{ key: "Referrer-Policy", value: "no-referrer" }],
      })),
      {
        source: "/styleguide",
        headers: [{ key: "X-Robots-Tag", value: "noindex, nofollow" }],
      },
      // ROUTES §B2: the admin is never indexed, including its public invitation page (SEO-13).
      { source: "/admin/:path*", headers: [{ key: "X-Robots-Tag", value: "noindex, nofollow" }] },
      { source: "/models/:path*", headers: [{ key: "Cache-Control", value: PUBLIC_ASSET_CACHE }] },
      { source: "/images/:path*", headers: [{ key: "Cache-Control", value: PUBLIC_ASSET_CACHE }] },
    ];
  },
};

export default nextConfig;
